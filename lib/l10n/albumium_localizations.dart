class AlbumiumLocalizationsDelegate
    extends LocalizationsDelegate<AlbumiumLocalizations> {
  const AlbumiumLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => AlbumiumLocalizations.supportedLocales.any(
    (supported) => supported.languageCode == locale.languageCode,
  );

  @override
  Future<AlbumiumLocalizations> load(Locale locale) =>
      SynchronousFuture(AlbumiumLocalizations(locale));

  @override
  bool shouldReload(AlbumiumLocalizationsDelegate old) => false;
}

extension AlbumiumLocalizationContext on BuildContext {
  String tr(String turkish, {Map<String, Object> values = const {}}) =>
      (AlbumiumLocalizations.maybeOf(this) ??
              const AlbumiumLocalizations(Locale('tr')))
          .text(turkish, values: values);
}
